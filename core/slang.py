"""校园黑话 → 正式名词的静态检索扩展。

新生首问最口语化，却不经过 rewrite_query（首问无历史直接返回），黑话的
BM25 词面对不上正式文档、小模型向量对校园专名也不可靠——在检索入口把
命中词条的正式说法追加到 query 尾部，两路召回和重排共用扩展后的 query。

词条只收「文档里用正式名词、同学口中用黑话」的映射（素材来自知识库的
特色黑话文档和常见简称）；正式名词本身已经可检索的不收。攒到新的黑话
miss（看 tests/eval_retrieval.py 的 miss 清单）就往这里加一条。
"""

# 收录门槛：词条必须在日常提问里几乎无歧义。子串匹配没有分词边界，
# 像「小白」（口语=新手，还会命中小白菜）、「求科」（"要求科研"的子串）
# 这类高误伤词条宁可不收——扩展错一次污染整条检索链路。
SLANG = {
    "竺院": "竺可桢学院",
    "转系": "转专业",
    "保研": "推荐免试",
    "一卡通": "校园卡",
    "校卡": "校园卡",
    "彩票系统": "选课系统 教务管理系统",
    "考试周": "期末考试",
    "宝宝巴士": "校内巴士",
    "铛铛车": "校内巴士",
    "堕落街": "龙宇街",
    "留食": "澄月餐厅",
    "学霸餐": "麦香餐厅 盒饭",
    "蟹老板": "月牙楼 校史馆",
    "玉湖": "竺可桢学院 玉湖园区",
}


def expand_query(query: str) -> str:
    """命中词条时把正式说法追加到 query 尾部；未命中原样返回。"""
    extra = [
        formal for slang, formal in SLANG.items()
        if slang in query and formal not in query
    ]
    return f"{query} {' '.join(extra)}" if extra else query

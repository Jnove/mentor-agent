def _root_with_release_files(base: Path) -> Path:
    root = base / "repo"
    (root / "knowledge_base" / "政策").mkdir(parents=True)
    (root / "knowledge_base" / "政策" / "official.md").write_text("official", encoding="utf-8")
    (root / "requirements.lock").write_text(
        "# This file is autogenerated by pip-compile with Python 3.12\n",
        encoding="utf-8",
    )
    return root


def test_load_dotenv_file():
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / ".env"
        path.write_text("\ufeff# comment\nexport A='one'\nB=two # note\nEMPTY=\n", encoding="utf-8")
        assert load_dotenv_file(path) == {"A": "one", "B": "two", "EMPTY": ""}


def test_production_preflight_accepts_valid_config():
    with tempfile.TemporaryDirectory() as tmp:
        root = _root_with_release_files(Path(tmp))
        checks = validate(_valid_env(), root, "production", min_docs=1)
        assert not [c for c in checks if c.level == "ERROR"], checks


def test_production_preflight_blocks_unsafe_config():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp) / "repo"
        (root / "knowledge_base" / "政策").mkdir(parents=True)
        (root / "knowledge_base" / "政策" / "示例_政策.md").write_text("demo", encoding="utf-8")
        env = _valid_env()
        env.update({
            "LLM_API_KEY": "sk-xxxxxxxx",
            "LLM_BASE_URL": "http://localhost:1234/v1",
            "AUTH_SECRET": "short",
            "EMBED_BACKEND": "hash",
            "SMTP_HOST": "",
        })
        checks = validate(env, root, "production", min_docs=1)
        names = {c.name for c in checks if c.level == "ERROR"}
        assert {"LLM_API_KEY", "LLM_BASE_URL host", "AUTH_SECRET",
                "EMBED_BACKEND", "SMTP_HOST", "knowledge_base",
                "requirements.lock"}.issubset(names), checks



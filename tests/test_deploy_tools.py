def test_backup_and_restore_to_empty_directory():
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp)
        root = base / "source"
        for name in ("knowledge_base", "chroma_db", "data"):
            (root / name).mkdir(parents=True)
        (root / "knowledge_base" / "policy.md").write_text("policy", encoding="utf-8")
        (root / "chroma_db" / "index.bin").write_bytes(b"index")
        (root / "data" / "auth.db").write_bytes(b"sqlite")

        try:
            create_backup(root, base / "backups")
            assert False, "未确认 app 停止时必须拒绝"
        except ValueError:
            pass

        archive = create_backup(root, base / "backups", confirm_app_stopped=True)
        assert stat.S_IMODE(archive.stat().st_mode) == 0o600
        destination = base / "restored"
        manifest = restore_backup(archive, destination)
        assert manifest["schema"] == 1
        assert (destination / "knowledge_base" / "policy.md").read_text() == "policy"
        assert (destination / "data" / "auth.db").read_bytes() == b"sqlite"

        (base / "not-empty").mkdir()
        (base / "not-empty" / "keep.txt").write_text("keep")
        try:
            restore_backup(archive, base / "not-empty")
            assert False, "禁止覆盖非空目录"
        except ValueError:
            pass


